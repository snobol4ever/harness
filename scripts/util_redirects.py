#!/usr/bin/env python3
# util_redirects.py -- THE REDIRECT MAP FOR EVERY RETIRED PAGE AND RULING (box-scheduler step 17, CTO-496; the cio, 2026-11-04).
#
# A retired page or a closed ruling series is still cited by the live text (MEASURED 2026-11-04: 969 of 1129 distinct cited page names were not
# on disk; 10506 CEO-NNNN citations after the fired seat's record was deleted on Lon's word, CTO-487). The map .github/REDIRECTS.tsv says, for
# every .md page that git history deleted from .github and for every ruling series, where it lives now and the one command that reads it. It is
# GENERATED from git history and from RETIRED-ARCH-PAGES.tsv (the successor skills the 2026-11-01 consolidation named), never edited by hand.
#
#   util_redirects.py --regenerate          write .github/REDIRECTS.tsv from git history (idempotent; prints REGENERATED rows=N)
#   util_redirects.py --check               rc 0 when the map is current (every deleted page has a row, no row names a live page); rc 1 when not
#   util_redirects.py --sweep               scan the live text for citations of pages and rulings; print
#                                           REDIRECTS stale_citations=N retired_pages=P redirected_citations=C unresolved_names=U ruling_series=S files_scanned=F
#                                           rc 0 when stale_citations=0, rc 1 otherwise. A STALE citation names a page git history retired that has no
#                                           redirect row. An UNRESOLVED name was never a page anywhere this tool can see (a typo, a placeholder, another
#                                           repo's file); it is listed under /tmp/s4e/<seat>/redirects.unresolved.tsv and is not a stale citation.
#   util_redirects.py --resolve <name|ID>   print the redirect row for a page name (ARCH-ENGINE.md) or a ruling id (CEO-2041); rc 1 when none
#   util_redirects.py --probe               prove the sweep on a scratch copy: a map with one row removed reads stale_citations>0, the full map 0
#
# Scope of the sweep: .github/*.md, .github/skills/*/*.md, .github/digest/parts/*.md, harness/scripts/*.sh and *.py, the root's CLAUDE.md. A cited
# name resolves when a file of that basename exists under .github (any depth), at the root, or in /home/resources/postoffice (top level and one
# level down; every *.task.md is a baton there). Refusals are rc 2 and say why (CEO-1680). Env: S4E_HOME (the root; default the script's root).
import os, re, subprocess, sys, tempfile, shutil
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.environ.get("S4E_HOME") or os.path.dirname(os.path.dirname(HERE))
GH = os.path.join(ROOT, ".github")
MAP = os.path.join(GH, "REDIRECTS.tsv")
RETIRED_ARCH = os.path.join(GH, "RETIRED-ARCH-PAGES.tsv")
POST = os.environ.get("S4E_POST", "/home/resources/postoffice")
SEAT = os.environ.get("S4E_SEAT", "cio")
RULING_SERIES = [("CTO", "GOAL-CTO.md"), ("COO", "GOAL-COO.md"), ("CIO", "GOAL-CIO.md"), ("CAO", "GOAL-CAO.md"), ("CFO", "GOAL-CFO.md"), ("CQO", "GOAL-CQO.md")]
HEADER = ("# REDIRECTS.tsv -- WHERE EVERY RETIRED PAGE AND RULING LIVES NOW (box-scheduler step 17, CTO-496). GENERATED by harness/scripts/util_redirects.py --regenerate\n"
          "# from .github's git history and RETIRED-ARCH-PAGES.tsv; NEVER EDITED BY HAND (--check reads red when a deleted page lacks a row). Find one: util_redirects.py --resolve <name|ID>.\n"
          "# kind: page (a .md git deleted from .github), ruling-series (one row per NNNN series; CEO-1..CEO-2133 is closed, CTO-469). successor: the skill(s) or page that carry it, or history.\n"
          "kind\tname\tretired_commit\tretired_date\tsuccessor\tread\n")


def refuse(msg):
    print("REFUSE(2): " + msg, file=sys.stderr); sys.exit(2)


def git(*args):
    r = subprocess.run(["git", "-C", GH] + list(args), capture_output=True, text=True)
    if r.returncode != 0:
        refuse("git %s: %s" % (" ".join(args), r.stderr.strip()[:200]))
    return r.stdout


def deleted_pages():
    out = git("log", "--diff-filter=D", "--name-only", "--date=short", "--pretty=format:@@%h %ad", "--", "*.md")
    seen = {}
    commit = date = None
    for line in out.splitlines():
        if line.startswith("@@"):
            commit, date = line[2:].split(" ", 1); continue
        p = line.strip()
        if not p or p in seen or p.startswith("digest/") or p.startswith("skills/"):
            continue
        if os.path.exists(os.path.join(GH, p)):
            continue
        seen[p] = (commit, date)
    return seen


def arch_successors():
    s = {}
    if not os.path.exists(RETIRED_ARCH):
        return s
    for line in open(RETIRED_ARCH, encoding="utf-8", errors="replace"):
        if line.startswith("#") or line.startswith("page\t"):
            continue
        f = line.rstrip("\n").split("\t")
        if len(f) >= 3 and f[0].endswith(".md"):
            s[f[0]] = f[2]
    return s


def build_rows():
    succ = arch_successors()
    rows = []
    for path, (commit, date) in sorted(deleted_pages().items()):
        base = os.path.basename(path)
        rows.append(("page", path, commit, date, succ.get(base, "history"), "git -C .github show %s^:%s" % (commit, path)))
    ceo = [r for r in rows if r[1] == "GOAL-CEO.md"]
    if ceo:
        c = ceo[0]
        rows.append(("ruling-series", "CEO-NNNN", c[2], c[3], "GOAL-CTO.md (the series closed at CEO-2133; rulings continue as CTO-NNNN, CTO-469; alias R-NNNN, CIO-1)", "git -C .github show %s^:GOAL-CEO.md | grep -n 'CEO-NNNN'" % c[2]))
    for prefix, goal in RULING_SERIES:
        if os.path.exists(os.path.join(GH, goal)):
            rows.append(("ruling-series", prefix + "-NNNN", "-", "-", goal + " (LIVE CURSOR)", "grep -n '%s-NNNN' .github/%s" % (prefix, goal)))
    return rows


def render(rows):
    return HEADER + "".join("\t".join(r) + "\n" for r in rows)


def load_map():
    if not os.path.exists(MAP):
        return None
    rows = []
    for line in open(MAP, encoding="utf-8", errors="replace"):
        if line.startswith("#") or line.startswith("kind\t") or not line.strip():
            continue
        f = line.rstrip("\n").split("\t")
        if len(f) == 6:
            rows.append(tuple(f))
    return rows


def regenerate():
    rows = build_rows()
    text = render(rows)
    cur = open(MAP, encoding="utf-8", errors="replace").read() if os.path.exists(MAP) else None
    if cur == text:
        print("REGENERATED rows=%d unchanged %s" % (len(rows), os.path.relpath(MAP, ROOT))); return 0
    tmp = MAP + ".tmp.%d" % os.getpid()
    open(tmp, "w", encoding="utf-8").write(text); os.replace(tmp, MAP)
    print("REGENERATED rows=%d wrote %s" % (len(rows), os.path.relpath(MAP, ROOT))); return 0


def check():
    rows = load_map()
    if rows is None:
        print("REDIRECTS-CHECK missing %s (run --regenerate)" % os.path.relpath(MAP, ROOT)); return 1
    want = render(build_rows())
    have = open(MAP, encoding="utf-8", errors="replace").read()
    if want != have:
        wn = set(l.split("\t")[1] for l in want.splitlines() if l and not l.startswith("#") and not l.startswith("kind\t"))
        hn = set(r[1] for r in rows)
        print("REDIRECTS-CHECK stale: missing=%d extra=%d (run --regenerate)" % (len(wn - hn), len(hn - wn))); return 1
    print("REDIRECTS-CHECK current rows=%d" % len(rows)); return 0


def scope_files():
    files = []
    for pat in [("", "*.md"), ("skills", "*/*.md"), ("digest/parts", "*.md")]:
        import glob
        files += glob.glob(os.path.join(GH, pat[0], pat[1]))
    import glob as g
    files += g.glob(os.path.join(ROOT, "harness", "scripts", "*.sh")) + g.glob(os.path.join(ROOT, "harness", "scripts", "*.py"))
    if os.path.exists(os.path.join(ROOT, "CLAUDE.md")):
        files.append(os.path.join(ROOT, "CLAUDE.md"))
    return sorted(set(os.path.abspath(f) for f in files if os.path.isfile(f)))


def live_basenames():
    names = set()
    for d, subdirs, fs in os.walk(GH):
        subdirs[:] = [s for s in subdirs if s != ".git"]
        for f in fs:
            if f.endswith(".md"):
                names.add(f)
    for f in os.listdir(ROOT):
        if f.endswith(".md"):
            names.add(f)
    if os.path.isdir(POST):
        for f in os.listdir(POST):
            p = os.path.join(POST, f)
            if f.endswith(".md"):
                names.add(f)
            elif os.path.isdir(p) and f != "tasks":
                try:
                    names.update(x for x in os.listdir(p) if x.endswith(".md"))
                except OSError:
                    pass
    return names


NAME_RE = re.compile(r"(?<![A-Za-z0-9_./-])([A-Za-z0-9][A-Za-z0-9_.-]*\.md)(?![A-Za-z0-9_-])")
RULING_RE = re.compile(r"\b(CEO|R|CTO|COO|CIO|CAO|CFO|CQO)-(\d{1,4})\b")
ALIAS = {"R": "CEO"}   # CIO-1 (2026-11-04): R-NNNN is the alias of the closed series CEO-NNNN; both resolve to the one CEO-NNNN row


def sweep(map_rows=None, quiet=False):
    rows = load_map() if map_rows is None else map_rows
    if rows is None:
        refuse("no %s; run --regenerate first" % os.path.relpath(MAP, ROOT))
    by_base = {}
    series = set()
    for r in rows:
        if r[0] == "page":
            by_base.setdefault(os.path.basename(r[1]), r)
        elif r[0] == "ruling-series":
            series.add(r[1].split("-")[0])
    history = set(os.path.basename(p) for p in deleted_pages())
    live = live_basenames()
    mapbase = os.path.basename(MAP)
    stale = {}; redirected = 0; unresolved = {}; files = 0; ruling_stale = 0
    for f in scope_files():
        try:
            text = open(f, encoding="utf-8", errors="replace").read()
        except OSError:
            continue
        files += 1
        rel = os.path.relpath(f, ROOT)
        for m in NAME_RE.finditer(text):
            n = m.group(1)
            if n in live or n.endswith(".task.md") or n == mapbase:
                continue
            if n in by_base:
                redirected += 1
            elif n in history:
                stale.setdefault(n, []).append(rel)
            else:
                unresolved.setdefault(n, []).append(rel)
        for m in RULING_RE.finditer(text):
            if ALIAS.get(m.group(1), m.group(1)) in series:
                redirected += 1
            else:
                ruling_stale += 1
    nstale = sum(len(v) for v in stale.values()) + ruling_stale
    outdir = os.path.join("/tmp/s4e", SEAT)
    try:
        os.makedirs(outdir, exist_ok=True)
        with open(os.path.join(outdir, "redirects.unresolved.tsv"), "w") as fh:
            for n in sorted(unresolved, key=lambda k: -len(unresolved[k])):
                fh.write("%s\t%d\t%s\n" % (n, len(unresolved[n]), " ".join(sorted(set(unresolved[n]))[:6])))
        with open(os.path.join(outdir, "redirects.stale.tsv"), "w") as fh:
            for n in sorted(stale):
                fh.write("%s\t%d\t%s\n" % (n, len(stale[n]), " ".join(sorted(set(stale[n]))[:6])))
    except OSError:
        pass
    line = "REDIRECTS stale_citations=%d retired_pages=%d redirected_citations=%d unresolved_names=%d ruling_series=%d files_scanned=%d map=%s" % (
        nstale, len([r for r in rows if r[0] == "page"]), redirected, len(unresolved), len(series), files, os.path.relpath(MAP, ROOT))
    if not quiet:
        print(line)
        if stale:
            print("  stale pages (no redirect row): " + " ".join(sorted(stale)[:12]) + (" ..." if len(stale) > 12 else ""))
    return 0 if nstale == 0 else 1


def resolve(key):
    rows = load_map()
    if rows is None:
        refuse("no %s; run --regenerate first" % os.path.relpath(MAP, ROOT))
    m = RULING_RE.fullmatch(key)
    hits = []
    for r in rows:
        if m and r[0] == "ruling-series" and r[1].startswith(ALIAS.get(m.group(1), m.group(1)) + "-"):
            hits.append(tuple(x.replace("NNNN", m.group(2)) if i in (1, 5) else x for i, x in enumerate(r)))
        elif not m and (r[1] == key or os.path.basename(r[1]) == key):
            hits.append(r)
    if not hits:
        print("NO-REDIRECT %s (not a retired page, not a ruling series)" % key); return 1
    for h in hits:
        print("REDIRECT kind=%s name=%s retired=%s@%s successor=%s\n  read: %s" % (h[0], h[1], h[2], h[3], h[4], h[5]))
    return 0


def probe():
    rows = build_rows()
    pages = [r for r in rows if r[0] == "page"]
    if not pages:
        refuse("probe: git history shows no deleted page to remove")
    full = sweep(rows, quiet=True)
    cited = None
    hist = set(os.path.basename(r[1]) for r in pages)
    for f in scope_files():
        try:
            text = open(f, encoding="utf-8", errors="replace").read()
        except OSError:
            continue
        for m in NAME_RE.finditer(text):
            if m.group(1) in hist:
                cited = m.group(1); break
        if cited:
            break
    if cited is None:
        refuse("probe: no live file cites a retired page, the mutant cannot read red")
    mutant = [r for r in rows if os.path.basename(r[1]) != cited]
    cut = sweep(mutant, quiet=True)
    ok = full == 0 and cut == 1
    print("PROBE full_map_rc=%d mutant_without_%s_rc=%d %s" % (full, cited, cut, "GREEN" if ok else "RED"))
    return 0 if ok else 1


def main(argv):
    if len(argv) < 2:
        print(__doc__ or "usage: util_redirects.py --regenerate|--check|--sweep|--resolve <name|ID>|--probe", file=sys.stderr); return 2
    if not os.path.isdir(os.path.join(GH, ".git")) and not os.path.isfile(os.path.join(GH, ".git")):
        refuse("%s is not a git checkout" % GH)
    v = argv[1]
    if v == "--regenerate":
        return regenerate()
    if v == "--check":
        return check()
    if v == "--sweep":
        return sweep()
    if v == "--resolve":
        if len(argv) < 3:
            refuse("--resolve needs a page name or a ruling id")
        return resolve(argv[2])
    if v == "--probe":
        return probe()
    refuse("unknown verb %s" % v)


if __name__ == "__main__":
    sys.exit(main(sys.argv))
