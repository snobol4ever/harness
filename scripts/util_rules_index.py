#!/usr/bin/env python3
# util_rules_index.py -- THE ONE-PAGE RULES INDEX (box-scheduler step 17, CTO-496; the cio, 2026-11-04).
#
# RULES.md is the only law and it is 542 KB with 73 sections (MEASURED 2026-11-04); nobody reads it whole, so every seat quotes it from memory.
# .github/RULES-INDEX.md is one page, at most 16384 bytes, GENERATED from the `## ` headings of RULES.md: one line per section with its line
# range, its size and a short title, then where the other records live (MODE, the rulings, the redirect map, the skills). A seat reads a section
# by the line range the index prints. Never edited by hand: --check reads red when RULES.md moved under it.
#
#   util_rules_index.py --regenerate     write .github/RULES-INDEX.md (prints INDEX sections=N bytes=B)
#   util_rules_index.py --check          rc 0 when the index matches RULES.md and is within the cap; rc 1 when not
#   util_rules_index.py --print          print the index to stdout without writing
# Refusals are rc 2 (no RULES.md, or the index cannot fit the cap at the shortest title width). Env: S4E_HOME (the root; default the script's root).
import os, re, sys
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.environ.get("S4E_HOME") or os.path.dirname(os.path.dirname(HERE))
GH = os.path.join(ROOT, ".github")
RULES = os.path.join(GH, "RULES.md")
INDEX = os.path.join(GH, "RULES-INDEX.md")
CAP = 16384
MARKS = re.compile(r"^[\s⛔⭐✅✔❌⚠️🔒🔥📌📎•·—–-]+")


def refuse(msg):
    print("REFUSE(2): " + msg, file=sys.stderr); sys.exit(2)


def sections():
    lines = open(RULES, encoding="utf-8", errors="replace").read().split("\n")
    out = []
    for i, l in enumerate(lines, 1):
        if l.startswith("## "):
            out.append([i, l[3:].strip(), 0])
    for k, s in enumerate(out):
        end = out[k + 1][0] - 1 if k + 1 < len(out) else len(lines)
        s[2] = sum(len(x) + 1 for x in lines[s[0] - 1:end])
        s.append(end)
    return out


def short_title(h, width):
    t = MARKS.sub("", h)
    t = re.sub(r"\s*\((?:Lon|cto|coo|hq_|the |landed|proposed|ratified|20\d\d)[^)]*\)?.*$", "", t) if "(" in t else t
    t = re.sub(r"^(?:FACT RULES?|THE INSTRUMENT LAWS)\s*[—–-]+\s*", "", t)
    t = re.sub(r"\s+", " ", t).strip(" :;,.")
    if len(t) > width:
        t = t[:width - 1].rstrip() + "…"
    return t or h[:width]


def render(width):
    secs = sections()
    head = ("# RULES-INDEX.md -- THE ONE PAGE OVER RULES.md (box-scheduler step 17, CTO-496). GENERATED by harness/scripts/util_rules_index.py --regenerate; never edited by hand.\n"
            "RULES.md is the only law (%d sections, %d bytes). Read a section by its lines: `sed -n 'A,Bp' .github/RULES.md`. The rulings are the CTO-NNNN bullets of GOAL-CTO.md's LIVE CURSOR "
            "(the CEO-1..2133 series is closed and read from git history); a retired page or ruling is found by `python3 harness/scripts/util_redirects.py --resolve <name|ID>` (.github/REDIRECTS.tsv). "
            "MODE is `/home/resources/postoffice/MODE` (line 1 the mode, line 2 the current block, keyed ROSTER: LANES: ORDER-OF-WORK: BOSSES:). The skills under .github/skills/ carry each layer's design.\n\n"
            "## Sections (line range, size, title)\n") % (len(secs), os.path.getsize(RULES))
    body = "".join("- L%d-%d (%dK) %s\n" % (s[0], s[3], max(1, s[2] // 1024), short_title(s[1], width)) for s in secs)
    tail = ("\n## Where the rest lives\n"
            "- MODE and its archive: /home/resources/postoffice/MODE, MODE.archive (step 14); the bus: harness/scripts/s4e_msg.sh (skill fleet-bus).\n"
            "- Rulings: .github/GOAL-CTO.md (CTO-NNNN), GOAL-COO.md, GOAL-CIO.md, GOAL-CAO.md, GOAL-CFO.md, GOAL-CQO.md; each seat's GOAL file is its cursor.\n"
            "- Retired pages: .github/REDIRECTS.tsv (every .md git deleted, with the command that reads it) and RETIRED-ARCH-PAGES.tsv (the ARCH pages' successor skills).\n"
            "- Scope: ANNOUNCEMENT.md in the postoffice. Designs: each DESIGN-PLAN lives in its owning skill's DESIGN section and corpus/tests/shared/<design>/STEPS.tsv.\n")
    return head + body + tail


def fit():
    for width in (110, 96, 84, 72, 60, 48):
        t = render(width)
        if len(t.encode("utf-8")) <= CAP:
            return t
    refuse("the index cannot fit %d bytes at a 48-column title" % CAP)


def main(argv):
    if not os.path.isfile(RULES):
        refuse("no %s" % RULES)
    v = argv[1] if len(argv) > 1 else ""
    text = fit()
    n = len(sections()); b = len(text.encode("utf-8"))
    if v == "--print":
        sys.stdout.write(text); return 0
    if v == "--regenerate":
        cur = open(INDEX, encoding="utf-8", errors="replace").read() if os.path.exists(INDEX) else None
        if cur != text:
            tmp = INDEX + ".tmp.%d" % os.getpid(); open(tmp, "w", encoding="utf-8").write(text); os.replace(tmp, INDEX)
        print("INDEX sections=%d bytes=%d %s %s" % (n, b, "unchanged" if cur == text else "wrote", os.path.relpath(INDEX, ROOT))); return 0
    if v == "--check":
        cur = open(INDEX, encoding="utf-8", errors="replace").read() if os.path.exists(INDEX) else None
        if cur is None:
            print("INDEX-CHECK missing %s (run --regenerate)" % os.path.relpath(INDEX, ROOT)); return 1
        if cur != text:
            print("INDEX-CHECK stale: RULES.md moved under the index (run --regenerate)"); return 1
        print("INDEX-CHECK current sections=%d bytes=%d" % (n, b)); return 0
    print("usage: util_rules_index.py --regenerate|--check|--print", file=sys.stderr); return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv))
