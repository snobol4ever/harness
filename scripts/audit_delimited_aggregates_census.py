    nm = [("templates/x86/x86_asm.h", r"X86_IS_PORTMARK", "the port mark of the TEXT medium: emitter bookkeeping, never a stored value"),
          ("runtime/gone.c", r"never", "a declaration whose site is gone")]
    sites, defs, tables, exempt, stale = census(src, nm)
    want = {("by_name_dispatch.c", 3, "__rk_count", "RAKU", "macro", ""), ("by_name_dispatch.c", 7, "__pas_join", "PASCAL", "macro", ""),
            ("by_name_dispatch.c", 9, "other_split", "OTHER", "literal", ""), ("aggregates.c", 1, "agg_key", "REGISTRY_KEY", "literal", ""),
            ("pascal.y", 1, "init_lit", "PASCAL", "literal", ""),
            ("by_name_dispatch.c", 12, "script_try_call_builtin_by_name", "RAKU", "macro", "hash_get"),
            ("by_name_dispatch.c", 13, "script_try_call_builtin_by_name", "PASCAL", "macro", "__pas_ca_encode"),
            ("by_name_dispatch.c", 14, "script_try_call_builtin_by_name", "OTHER", "macro", "mystery")}
    got = {(os.path.basename(s[0]), s[1], s[2], s[3], s[4], s[6]) for s in sites}
    bad = 0
    if got != want:
        print("SELFTEST FAIL: member sites read %s, want %s" % (sorted(got), sorted(want))); bad = 1
    if sorted(d_[2] for d_ in defs) != ["MON_US", "SOH"]:
        print("SELFTEST FAIL: separator definitions read %s, want ['MON_US', 'SOH']" % [d_[2] for d_ in defs]); bad = 1
