def main(argv):
    if "--selftest" in argv:
        return selftest()
    d = "src"; tsv = None; base = None; nmf = None; top = 12
    for i, a in enumerate(argv):
        if a == "--dir": d = argv[i + 1]
        if a == "--tsv": tsv = argv[i + 1]
        if a == "--baseline": base = argv[i + 1]
        if a == "--non-members": nmf = argv[i + 1]
        if a == "--top": top = int(argv[i + 1])
    if nmf is None:
        cand = os.path.join(os.path.dirname(os.path.abspath(__file__)), "fixtures", "delimited", "NON_MEMBERS.tsv")
        nmf = cand if os.path.isfile(cand) else None
    sites, defs, tables, exempt, stale = census(d, load_non_members(nmf))
    if tsv:
        with open(tsv, "w") as f:
            f.write("file\tline\tfunction\tcarrier\tkind\ttext\tanchor\n")
            for s in sites:
                f.write("%s\t%d\t%s\t%s\t%s\t%s\t%s\n" % s)
    baseline = read_baseline(base) if base else None
    return report(d, sites, defs, tables, exempt, stale, top, baseline)


if __name__ == "__main__":
    sys.exit(main(sys.argv))
