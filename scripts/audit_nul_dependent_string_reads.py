#!/usr/bin/env python3
"""audit_nul_dependent_string_reads.py [--src DIR] [--check | --update | --selftest] [--baseline FILE] [--tsv OUT] [--top N]

The ratchet over NUL-DEPENDENT READS OF A DESCRIPTOR'S STRING (CTO-397, relayed by the ceo 2026-10-29; the brief line is "No strlen on a descriptor's .s").
A descriptor string carries its length (slen) and may hold a NUL byte -- a SNOBOL4 string, a Prolog atom, an Icon string -- and a C read that stops at the
first NUL (strlen, strcmp, strncmp, strchr, strstr, strcpy, strdup, ct_strdup, atoi and the strto family, puts and fputs, a printf-family call whose
format has a %s) of a descriptor's .s silently truncates it.  The census walks src/runtime, src/driver, src/emitter and src/parsers (.c .h .cpp .inc,
the bison and flex output set aside), takes every call of those functions whose ARGUMENT TEXT (balanced parentheses, string literals masked) names a
descriptor string -- a member access .s or ->s, a tree literal .sval or ->sval, or a call of prolog_atom_name -- and counts them per file.  A printf-family
call counts only when its format literal holds a %s directive (any flags, width or precision).  It is a heuristic over text, not a verdict: a member named
s of some other struct is counted until its file's count is argued down; the point is that the count may only fall.

Two columns, both ratcheted (the cto, ARCH-PROLOG-DATABASE section 13 (5)): TRUNCATING reads copy or measure up to the first NUL and so lose the rest of the string (strlen, strdup,
ct_strdup, strcpy and the strn family that copy, atoi and the strto family, sscanf, puts, fputs, a printf-family %s) and EQUALITY reads compare or search up to it (strcmp, strncmp,
strcasecmp, strchr, strstr and their kin); the truncating column is what a NUL-in-a-string row lowers first, and a keyword compare of an atom holding a NUL stays counted in its own column.

    --check     rc 0 when no file's count rose in either column and no new file appears (a file whose count fell prints LOWER: run --update), rc 1 otherwise, rc 2 without a baseline
    --update    rewrites the baseline, and only downward: rc 1 and nothing written when any file rose in either column or a new file appears; a missing baseline is created
    --selftest  builds a scratch tree with every declared form and refuses a census that miscounts one
    --src DIR   the source root holding runtime/ driver/ emitter/ parsers/ (default ../SCRIP/src); --tsv OUT writes file, line, call, kind, column, text; --top N rows of each table
"""
import os
import re
import sys
import tempfile
from collections import Counter, defaultdict

HERE = os.path.dirname(os.path.abspath(__file__))
DEFAULT_SRC = os.path.join(os.path.dirname(os.path.dirname(HERE)), "SCRIP", "src")
DEFAULT_BASELINE = os.path.join(HERE, "audit_nul_dependent_string_reads.baseline.tsv")
DIRS = ("runtime", "driver", "emitter", "parsers")
EXTS = (".c", ".h", ".cpp", ".inc")
GENERATED = re.compile(r"(A Bison parser|generated by flex|#define FLEX_SCANNER|yy_create_buffer|YYBISON)")
EQUALITY = "strcmp strncmp strcasecmp strncasecmp strchr strrchr strstr strcasestr strspn strcspn strpbrk".split()
TRUNCATING = ("strlen strcpy strncpy strcat strncat strdup strndup ct_strdup strtok atoi atol atoll atof strtol strtoll strtoul strtoull strtod sscanf puts fputs").split()
PLAIN = EQUALITY + TRUNCATING
COLUMNS = ("truncating", "equality")
FORMATTED = "printf fprintf dprintf snprintf sprintf vprintf vfprintf vsnprintf ct_snprintf".split()
CALL = re.compile(r"(?<![A-Za-z0-9_.>])(" + "|".join(sorted(PLAIN + FORMATTED, key=len, reverse=True)) + r")\s*\(")
EVIDENCE = re.compile(r"(?:\.|->)\s*(?:s|sval)(?![A-Za-z0-9_])(?!\s*\[)|(?<![A-Za-z0-9_])prolog_atom_name\s*\(")
SDIRECTIVE = re.compile(r"%[-+ #0]*(?:\d+|\*)?(?:\.(?:\d+|\*))?(?:hh|h|ll|l|L|z|j|t)?s")
STRLIT = re.compile(r'"(?:[^"\\\n]|\\.)*"')
CHRLIT = re.compile(r"'(?:[^'\\\n]|\\.)+'")
LOOKAHEAD = 6


def files_under(src):
    out = []
    for d in DIRS:
        for root, _, names in os.walk(os.path.join(src, d)):
            for n in sorted(names):
                if n.endswith(EXTS):
                    out.append(os.path.join(root, n))
    return sorted(out)


def mask(text):
    text = STRLIT.sub(lambda m: '"' + "_" * (len(m.group(0)) - 2) + '"', text)
    return CHRLIT.sub(lambda m: "'" + "_" * (len(m.group(0)) - 2) + "'", text)


def call_args(lines, i, col):
    depth, parts = 0, []
    for j in range(i, min(len(lines), i + LOOKAHEAD)):
        seg = lines[j][col:] if j == i else lines[j]
        for k, ch in enumerate(seg):
            if ch == "(":
                depth += 1
            elif ch == ")":
                depth -= 1
                if depth == 0:
                    parts.append(seg[: k + 1])
                    return "".join(parts)
        parts.append(seg)
    return "".join(parts)


def scan_file(path):
    try:
        text = open(path, errors="replace").read()
    except OSError:
        return []
    if GENERATED.search(text[:4096]):
        return []
    lines = text.split("\n")
    masked_lines = [mask(x) for x in lines]
    sites = []
    for i, line in enumerate(lines):
        if line.lstrip().startswith(("#include", "/*", "*", "//")):
            continue
        for m in CALL.finditer(masked_lines[i]):
            name = m.group(1)
            col = m.end() - 1
            raw_args = call_args(lines, i, col)
            masked_args = call_args(masked_lines, i, col)
            if not EVIDENCE.search(masked_args):
                continue
            if name in FORMATTED and not SDIRECTIVE.search(raw_args):
                continue
            kind = "format" if name in FORMATTED else "plain"
            sites.append((i + 1, name, kind, "equality" if name in EQUALITY else "truncating", line.strip()[:160]))
    return sites


def census(src):
    rows = []
    for p in files_under(src):
        rel = os.path.relpath(p, src)
        for ln, name, kind, column, text in scan_file(p):
            rows.append((rel, ln, name, kind, column, text))
    return rows


def per_file(rows):
    c = {}
    for r in rows:
        c.setdefault(r[0], [0, 0])[COLUMNS.index(r[4])] += 1
    return {f: tuple(v) for f, v in c.items()}


def total(counts):
    return sum(sum(v) for v in counts.values())


def read_baseline(path):
    out = {}
    for l in open(path):
        if l.startswith("#") or l.startswith("file\t") or not l.strip():
            continue
        f, t, e = l.rstrip("\n").split("\t")[:3]
        out[f] = (int(t), int(e))
    return out


def write_baseline(path, counts):
    with open(path, "w") as fh:
        fh.write("file\ttruncating\tequality\n")
        for f in sorted(counts):
            fh.write("%s\t%d\t%d\n" % (f, counts[f][0], counts[f][1]))


def report(rows, top):
    byfile, bycall, bykind, bycol = per_file(rows), Counter(r[2] for r in rows), Counter(r[3] for r in rows), Counter(r[4] for r in rows)
    print("NUL-dependent reads of a descriptor's string: %d site(s) in %d file(s)  [truncating %d, equality %d; plain %d, format %d]"
          % (len(rows), len(byfile), bycol["truncating"], bycol["equality"], bykind["plain"], bykind["format"]))
    print("by call:  " + ", ".join("%s %d" % (k, v) for k, v in bycall.most_common(top)))
    calls_by_file = defaultdict(Counter)
    for r in rows:
        calls_by_file[r[0]][r[2]] += 1
    print("by file, worst truncating first (truncating/equality):")
    for f, v in sorted(byfile.items(), key=lambda kv: (-kv[1][0], -kv[1][1], kv[0]))[:top]:
        print("  %4d/%-4d  %-60s %s" % (v[0], v[1], f, " ".join("%s:%d" % kv for kv in calls_by_file[f].most_common(4))))


def compare(current, base):
    rose, fell = [], []
    for f in sorted(set(current) | set(base)):
        c, b = current.get(f, (0, 0)), base.get(f, (0, 0))
        for k, col in enumerate(COLUMNS):
            if c[k] > b[k]:
                rose.append((f, col, b[k], c[k], f not in base))
            elif c[k] < b[k]:
                fell.append((f, col, b[k], c[k]))
    return rose, fell


def selftest():
    T, E, N = "truncating", "equality", None
    cases = {
        "runtime/pos.c": [
            ("n = strlen(d.s);", T), ("if (strcmp(a->s, b)) x();", E), ("p = strdup(v.sval);", T), ("q = ct_strdup(prolog_atom_name(a));", T),
            ('fprintf(f, "%s", d.s);', T), ('snprintf(buf, 8, "x=%-5.3s y", d.s);', T), ("fputs(d.s, out);", T), ("n = atoi(t->s);", T),
            ("r = strncmp(d.s, e, 4);", E), ("m = strlen(\n    d.s);", T), ("s = strstr(d.s, \"abc\");", E), ("c = strchr(d.s, 47);", E),
            ("p = strcpy(buf, d.s);", T), ("v = strtol(d.s, 0, 10);", T), ("k = strcasecmp(d.s, e);", E),
        ],
        "runtime/neg.c": [
            ("n = strlen(buf);", N), ('printf("%d\\n", d.slen);', N), ('printf("%s\\n", name);', N), ('puts("strlen(d.s)");', N), ("n = d.slen;", N),
            ('fprintf(f, "%d", d.s[0]);', N), ("x = memcmp(d.s, e, d.slen);", N), ("#include <strlen(d.s)>", N), ("y = my_strlen(d.s);", N),
            ("n = strlen(d.sp);", N), ("n = strlen(p.s2);", N), ("k = strcmp(e->s[i].nm, name);", N),
        ],
        "driver/gen.c": [("/* A Bison parser */\nn = strlen(d.s);", N)],
    }
    bad = 0
    with tempfile.TemporaryDirectory() as td:
        for rel, items in cases.items():
            os.makedirs(os.path.join(td, os.path.dirname(rel)), exist_ok=True)
            for k, (code, want) in enumerate(items):
                p = os.path.join(td, rel.replace(".c", "_%d.c" % k))
                open(p, "w").write(code + "\n")
        got = per_file(census(td))
        for rel, items in cases.items():
            for k, (code, want) in enumerate(items):
                key = rel.replace(".c", "_%d.c" % k)
                have = got.get(key, (0, 0))
                wanted = tuple(1 if want == col else 0 for col in COLUMNS)
                if have != wanted:
                    print("SELFTEST FAIL: %r read truncating/equality %s, wanted %s" % (code, have, wanted))
                    bad += 1
    print("SELFTEST %s: %d forms checked" % ("FAIL" if bad else "PASS", sum(len(v) for v in cases.values())))
    return 1 if bad else 0


def main(argv):
    src, baseline, tsv, top, mode = DEFAULT_SRC, DEFAULT_BASELINE, None, 15, None
    i = 1
    while i < len(argv):
        a = argv[i]
        if a in ("--check", "--update", "--selftest"):
            mode = a
        elif a in ("--src", "--baseline", "--tsv", "--top") and i + 1 < len(argv):
            i += 1
            if a == "--src":
                src = argv[i]
            elif a == "--baseline":
                baseline = argv[i]
            elif a == "--tsv":
                tsv = argv[i]
            else:
                top = int(argv[i])
        else:
            print(__doc__)
            return 2
        i += 1
    if mode == "--selftest":
        return selftest()
    if not os.path.isdir(src):
        print("REFUSE(2): no source tree at %s" % src)
        return 2
    rows = census(src)
    if tsv:
        with open(tsv, "w") as fh:
            for r in rows:
                fh.write("%s\t%d\t%s\t%s\t%s\t%s\n" % r)
    report(rows, top)
    current = per_file(rows)
    if mode is None:
        return 0
    if mode == "--update":
        if os.path.exists(baseline):
            rose, _ = compare(current, read_baseline(baseline))
            if rose:
                for f, col, b, n, _ in rose:
                    print("REFUSE(1): %s %s rose from %d to %d -- a baseline is only lowered" % (f, col, b, n))
                return 1
        write_baseline(baseline, current)
        print("baseline written: %d file(s), %d site(s) -> %s" % (len(current), total(current), baseline))
        return 0
    if not os.path.exists(baseline):
        print("REFUSE(2): no baseline at %s -- run --update once" % baseline)
        return 2
    rose, fell = compare(current, read_baseline(baseline))
    for f, col, b, n in fell:
        print("LOWER: %s %s fell from %d to %d -- run --update in this landing so the ratchet keeps the fall" % (f, col, b, n))
    for f, col, b, n, new in rose:
        print("RED: %s %s %s %d -> %d: a NUL-dependent read of a descriptor's string landed (read it by its slen)" % ("NEW FILE" if new else "ROSE", f, col, b, n))
    base = read_baseline(baseline)
    print("CHECK %s: %d site(s) [truncating %d, equality %d], baseline %d [truncating %d, equality %d]" % ("RED" if rose else "GREEN", total(current),
          sum(v[0] for v in current.values()), sum(v[1] for v in current.values()), total(base), sum(v[0] for v in base.values()), sum(v[1] for v in base.values())))
    return 1 if rose else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
