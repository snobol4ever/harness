#!/usr/bin/env python3
"""audit_nul_dependent_string_reads.py [--src DIR] [--check | --update | --selftest] [--baseline FILE] [--tsv OUT] [--top N]

The ratchet over NUL-DEPENDENT READS OF A DESCRIPTOR'S STRING (CTO-397, relayed by the ceo 2026-10-29; the brief line is "No strlen on a descriptor's .s").
A descriptor string carries its length (slen) and may hold a NUL byte -- a SNOBOL4 string, a Prolog atom, an Icon string -- and a C read that stops at the
first NUL (strlen, strcmp, strncmp, strchr, strstr, strcpy, strdup, ct_strdup, atoi and the strto family, puts and fputs, a printf-family call whose
format has a %s) of a descriptor's .s silently truncates it.  The census walks src/runtime, src/driver, src/emitter and src/parsers (.c .h .cpp .inc,
the bison and flex output set aside), takes every call of those functions whose ARGUMENT TEXT (balanced parentheses, string literals masked) names a
descriptor string -- a member access .s or ->s, a tree literal .sval or ->sval, or a call of prolog_atom_name -- and counts them per file.  A printf-family
call counts only when its format literal holds a %s directive (any flags, width or precision).  It is a heuristic over text, not a verdict: a member named
s of some other struct is counted until its file's count is argued down; the point is that the count may only fall.

    --check     rc 0 when no file's count rose and no new file appears (a file whose count fell prints LOWER: run --update), rc 1 otherwise, rc 2 without a baseline
    --update    rewrites the baseline, and only downward: rc 1 and nothing written when any file rose or a new file appears; a missing baseline is created
    --selftest  builds a scratch tree with every declared form and refuses a census that miscounts one
    --src DIR   the source root holding runtime/ driver/ emitter/ parsers/ (default ../SCRIP/src); --tsv OUT writes file, line, call, kind, text; --top N rows of each table
"""
import os
import re
import sys
import tempfile
from collections import Counter, defaultdict

HERE = os.path.dirname(os.path.abspath(__file__))
DEFAULT_SRC = os.path.join(os.path.dirname(os.path.dirname(HERE)), "SCRIP", "src")
DEFAULT_BASELINE = os.path.join(HERE, "audit_nul_dependent_string_reads.baseline.tsv")
DIRS = ("runtime", "driver", "emitter", "parsers")
EXTS = (".c", ".h", ".cpp", ".inc")
GENERATED = re.compile(r"(A Bison parser|generated by flex|#define FLEX_SCANNER|yy_create_buffer|YYBISON)")
PLAIN = ("strlen strcmp strncmp strcasecmp strncasecmp strchr strrchr strstr strcasestr strcpy strncpy strcat strncat strdup strndup ct_strdup "
         "strspn strcspn strpbrk strtok atoi atol atoll atof strtol strtoll strtoul strtoull strtod sscanf puts fputs").split()
FORMATTED = "printf fprintf dprintf snprintf sprintf vprintf vfprintf vsnprintf ct_snprintf".split()
CALL = re.compile(r"(?<![A-Za-z0-9_.>])(" + "|".join(sorted(PLAIN + FORMATTED, key=len, reverse=True)) + r")\s*\(")
EVIDENCE = re.compile(r"(?:\.|->)\s*(?:s|sval)(?![A-Za-z0-9_])(?!\s*\[)|(?<![A-Za-z0-9_])prolog_atom_name\s*\(")
SDIRECTIVE = re.compile(r"%[-+ #0]*(?:\d+|\*)?(?:\.(?:\d+|\*))?(?:hh|h|ll|l|L|z|j|t)?s")
STRLIT = re.compile(r'"(?:[^"\\\n]|\\.)*"')
CHRLIT = re.compile(r"'(?:[^'\\\n]|\\.)+'")
LOOKAHEAD = 6


def files_under(src):
    out = []
    for d in DIRS:
        for root, _, names in os.walk(os.path.join(src, d)):
            for n in sorted(names):
                if n.endswith(EXTS):
                    out.append(os.path.join(root, n))
    return sorted(out)


def mask(text):
    text = STRLIT.sub(lambda m: '"' + "_" * (len(m.group(0)) - 2) + '"', text)
    return CHRLIT.sub(lambda m: "'" + "_" * (len(m.group(0)) - 2) + "'", text)


def call_args(lines, i, col):
    depth, parts = 0, []
    for j in range(i, min(len(lines), i + LOOKAHEAD)):
        seg = lines[j][col:] if j == i else lines[j]
        for k, ch in enumerate(seg):
            if ch == "(":
                depth += 1
            elif ch == ")":
                depth -= 1
                if depth == 0:
                    parts.append(seg[: k + 1])
                    return "".join(parts)
        parts.append(seg)
    return "".join(parts)


def scan_file(path):
    try:
        text = open(path, errors="replace").read()
    except OSError:
        return []
    if GENERATED.search(text[:4096]):
        return []
    lines = text.split("\n")
    masked_lines = [mask(x) for x in lines]
    sites = []
    for i, line in enumerate(lines):
        if line.lstrip().startswith(("#include", "/*", "*", "//")):
            continue
        for m in CALL.finditer(masked_lines[i]):
            name = m.group(1)
            col = m.end() - 1
            raw_args = call_args(lines, i, col)
            masked_args = call_args(masked_lines, i, col)
            if not EVIDENCE.search(masked_args):
                continue
            if name in FORMATTED and not SDIRECTIVE.search(raw_args):
                continue
            kind = "format" if name in FORMATTED else "plain"
            sites.append((i + 1, name, kind, line.strip()[:160]))
    return sites


def census(src):
    rows = []
    for p in files_under(src):
        rel = os.path.relpath(p, src)
        for ln, name, kind, text in scan_file(p):
            rows.append((rel, ln, name, kind, text))
    return rows


def per_file(rows):
    c = Counter()
    for r in rows:
        c[r[0]] += 1
    return c


def read_baseline(path):
    out = {}
    for l in open(path):
        if l.startswith("#") or l.startswith("file\t") or not l.strip():
            continue
        f, n = l.rstrip("\n").split("\t")[:2]
        out[f] = int(n)
    return out


def write_baseline(path, counts):
    with open(path, "w") as fh:
        fh.write("file\tcount\n")
        for f in sorted(counts):
            fh.write("%s\t%d\n" % (f, counts[f]))


def report(rows, top):
    byfile, bycall, bykind = per_file(rows), Counter(r[2] for r in rows), Counter(r[3] for r in rows)
    print("NUL-dependent reads of a descriptor's string: %d site(s) in %d file(s)  [plain %d, format %d]" % (len(rows), len(byfile), bykind["plain"], bykind["format"]))
    print("by call:  " + ", ".join("%s %d" % (k, v) for k, v in bycall.most_common(top)))
    calls_by_file = defaultdict(Counter)
    for r in rows:
        calls_by_file[r[0]][r[2]] += 1
    print("by file, worst first:")
    for f, n in byfile.most_common(top):
        print("  %4d  %-60s %s" % (n, f, " ".join("%s:%d" % kv for kv in calls_by_file[f].most_common(4))))


def compare(current, base):
    rose = [(f, base.get(f, 0), n) for f, n in sorted(current.items()) if n > base.get(f, 0)]
    fell = [(f, b, current.get(f, 0)) for f, b in sorted(base.items()) if current.get(f, 0) < b]
    return rose, fell


def selftest():
    cases = {
        "runtime/pos.c": [
            ("n = strlen(d.s);", 1), ("if (strcmp(a->s, b)) x();", 1), ("p = strdup(v.sval);", 1), ("q = ct_strdup(prolog_atom_name(a));", 1),
            ('fprintf(f, "%s", d.s);', 1), ('snprintf(buf, 8, "x=%-5.3s y", d.s);', 1), ("fputs(d.s, out);", 1), ("n = atoi(t->s);", 1),
            ("r = strncmp(d.s, e, 4);", 1), ("m = strlen(\n    d.s);", 1), ("s = strstr(d.s, \"abc\");", 1),
        ],
        "runtime/neg.c": [
            ("n = strlen(buf);", 0), ('printf("%d\\n", d.slen);', 0), ('printf("%s\\n", name);', 0), ('puts("strlen(d.s)");', 0), ("n = d.slen;", 0),
            ('fprintf(f, "%d", d.s[0]);', 0), ("x = memcmp(d.s, e, d.slen);", 0), ("#include <strlen(d.s)>", 0), ("y = my_strlen(d.s);", 0),
            ("n = strlen(d.sp);", 0), ("n = strlen(p.s2);", 0), ("k = strcmp(e->s[i].nm, name);", 0),
        ],
        "driver/gen.c": [("/* A Bison parser */\nn = strlen(d.s);", 0)],
    }
    bad = 0
    with tempfile.TemporaryDirectory() as td:
        for rel, items in cases.items():
            os.makedirs(os.path.join(td, os.path.dirname(rel)), exist_ok=True)
            for k, (code, want) in enumerate(items):
                p = os.path.join(td, rel.replace(".c", "_%d.c" % k))
                open(p, "w").write(code + "\n")
        got = per_file(census(td))
        for rel, items in cases.items():
            for k, (code, want) in enumerate(items):
                key = rel.replace(".c", "_%d.c" % k)
                if got.get(key, 0) != want:
                    print("SELFTEST FAIL: %r read %d, wanted %d" % (code, got.get(key, 0), want))
                    bad += 1
    print("SELFTEST %s: %d forms checked" % ("FAIL" if bad else "PASS", sum(len(v) for v in cases.values())))
    return 1 if bad else 0


def main(argv):
    src, baseline, tsv, top, mode = DEFAULT_SRC, DEFAULT_BASELINE, None, 15, None
    i = 1
    while i < len(argv):
        a = argv[i]
        if a in ("--check", "--update", "--selftest"):
            mode = a
        elif a in ("--src", "--baseline", "--tsv", "--top") and i + 1 < len(argv):
            i += 1
            if a == "--src":
                src = argv[i]
            elif a == "--baseline":
                baseline = argv[i]
            elif a == "--tsv":
                tsv = argv[i]
            else:
                top = int(argv[i])
        else:
            print(__doc__)
            return 2
        i += 1
    if mode == "--selftest":
        return selftest()
    if not os.path.isdir(src):
        print("REFUSE(2): no source tree at %s" % src)
        return 2
    rows = census(src)
    if tsv:
        with open(tsv, "w") as fh:
            for r in rows:
                fh.write("%s\t%d\t%s\t%s\t%s\n" % r)
    report(rows, top)
    current = per_file(rows)
    if mode is None:
        return 0
    if mode == "--update":
        if os.path.exists(baseline):
            rose, _ = compare(current, read_baseline(baseline))
            if rose:
                for f, b, n in rose:
                    print("REFUSE(1): %s rose from %d to %d -- a baseline is only lowered" % (f, b, n))
                return 1
        write_baseline(baseline, current)
        print("baseline written: %d file(s), %d site(s) -> %s" % (len(current), sum(current.values()), baseline))
        return 0
    if not os.path.exists(baseline):
        print("REFUSE(2): no baseline at %s -- run --update once" % baseline)
        return 2
    rose, fell = compare(current, read_baseline(baseline))
    for f, b, n in fell:
        print("LOWER: %s fell from %d to %d -- run --update in this landing so the ratchet keeps the fall" % (f, b, n))
    for f, b, n in rose:
        print("RED: %s %s %d -> %d: a NUL-dependent read of a descriptor's string landed (read it by its slen)" % ("NEW FILE" if b == 0 else "ROSE", f, b, n))
    print("CHECK %s: %d site(s), baseline %d" % ("RED" if rose else "GREEN", sum(current.values()), sum(read_baseline(baseline).values())))
    return 1 if rose else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
