def comma_declarators(s, k):
    """(name, bound, dims) of every array declarator after the first in the declaration statement s[k:] -- `static long
    g_gc_rep_ranges[GC_REP_POPS], g_gc_rep_bytes[GC_REP_POPS], ...;` declares six tables and ARRAY, which needs a type word before
    each name, sees only the first. Stops at the statement's `;`, or at anything that is not a declarator."""
    n = len(s)

    def skip_init(j):
        while j < n and s[j] in " \t":
            j += 1
        if j < n and s[j] == "=" and s[j + 1:j + 2] != "=":
            d = 0
            j += 1
            while j < n:
                c = s[j]
                if c in "([{":
                    d += 1
                elif c in ")]}":
                    if d == 0:
                        return n
                    d -= 1
                elif d == 0 and c in ",;":
                    break
                j += 1
        return j
    j = skip_init(k)
    while j < n and s[j] == ",":
        m = re.compile(r",\s*\**\s*(?:const\s+)?([A-Za-z_]\w*)\s*(?:\[\s*(" + BOUND_RE + r")\s*\]((?:\s*\[[^\]]*\])*))?").match(s, j)
        if not m:
            return
        if m.group(2):
            yield m.group(1), m.group(2).strip(), (m.group(3) or "").replace(" ", "")
        j = skip_init(m.end())


def define_value(v):
    """a #define's value as a constant bound, or None: integer casts, U/L suffixes and outer parens dropped --
    `((uintptr_t)1 << PL_TR_ARENA_LG2)` is `1 << PL_TR_ARENA_LG2`, `((size_t)8u << 20)` is `8 << 20`, `4096UL` is `4096`."""
    v = re.sub(r"\(\s*(?:(?:unsigned|signed|const)\s+)*(?:char|short|int|long(?:\s+long)?|size_t|ssize_t|u?int\d+_t|u?intptr_t)\s*\)", "", v)
    v = re.sub(r"\b(0x[0-9a-fA-F]+|[0-9]+)[uUlL]+\b", r"\1", v).strip()
    while v.startswith("(") and v.endswith(")") and match_close(v, 0, "(", ")") == len(v) - 1:
        v = v[1:-1].strip()
    return v if re.fullmatch(BOUND_RE, v) else None


def load(path):
    try:
        return open(path, encoding="utf-8", errors="replace").read()
    except OSError:
        return ""


def resolve(bound, defines, depth=0):
    """the value of a constant bound (BOUND_RE), with C's precedence -- << below + below * -- and macros through defines; or None."""
    b = bound.strip()
    if depth > 8:
        return None
    for op in ("<<", "+", "*"):
        parts = [x for x in re.split(r"\s*" + re.escape(op) + r"\s*", b)] if op in b else None
        if parts and len(parts) > 1:
            vals = [resolve(x, defines, depth + 1) for x in parts]
            if any(v is None for v in vals):
                return None
            r = vals[0]
            for v in vals[1:]:
                r = (r << v) if op == "<<" else (r + v) if op == "+" else (r * v)
            return r
    if re.fullmatch(r"[0-9]+", b):
        return int(b)
    if re.fullmatch(r"0x[0-9a-fA-F]+", b):
        return int(b, 16)
    if b in defines:
        return resolve(defines[b], defines, depth + 1)
    return None


# ==================================================================== guard classification (CEO-1231) ===
# ⭐⭐ A GUARD IS A GROWTH OR A LOUD REFUSAL, NEVER A DROP (ceo CEO-1231 (2), 2026-09-24, on the coo's ask). Until this section the census
# read a table as "guarded" when its bound macro appeared in ANY comparison in its file -- so pl_list_to_arr's n < 4096, which keeps the
# write in bounds by failing silently, read the same as frame_layout.c's zv table, which aborts naming itself. Each comparison of a
# table's bound is now a SITE with a class:
#   LOUD      the at-cap path refuses: it reaches abort/exit/longjmp itself, or calls a function that refuses (error-shaped by name --
#             err/error/fatal/die/abort/refuse/panic/overflow/full -- AND reaching a primitive, refusing_functions below); a call that only
#             prints or records an error and returns is NOT a refusal (fc_reg_full's "TABLE FULL ... DROPPED", the cfo's reading)
#   DROP      the at-cap path does not refuse: a silent return/break/continue (DROP-silent), no else at all (DROP-skip), a loop that
#             stops early (`&& n < CAP`, DROP-truncate) or an assignment of the bound (DROP-clamp)
#   NEUTRAL   not a capacity guard: an index checked before a READ, or a loop over the whole table (`i < CAP` alone)
# and a table is LOUD when some site is LOUD and none DROPs, DROP when any site drops, NONE when no site guards a fill at all (never
# compared, or compared only as an index or an iteration). ⛔ A SITE BELONGS TO A TABLE ONLY BY EVIDENCE, never by sharing a number:
# its compared variable indexes the table (NAME[x], NAME[x++]) or carries the table's name as its stem (g_ab_fn_cell_n for
# g_ab_fn_cells), or the comparison is against sizeof NAME. Without that rule `256` in two hundred unrelated comparisons of one file was
# every 256-entry table's "guard". A DROP further needs the compared variable incremented AND the table written (NAME[...] =, &NAME[...],
# a copy into it) inside the SAME FUNCTION as the site -- a data-driven index checked before a read (`g >= MAX_GROUPS) continue;`) is
# NEUTRAL. A literal bound N matches N and N-1 (the NUL a char buffer keeps). A const table is reported, and read by the census lines as
# class A by rule: a program cannot write it. CALIBRATED 2026-09-24 against the cases named on the row: frame_layout.c's zls tables,
# emit.cpp g_strtab/g_csettab and g_ab_fn_cells, raku re.c group_name LOUD; driver_call.c call_stack (return FAILDESCR), emit.cpp
# g_gc_map_names (the cfo: drops past 8192), lower_snobol4.c DEFINE names, prolog_driver.c g_pl_consulted and rt.c g_call_args (past 64
# arguments, the defect hq_snobol4 isolated by hand the same morning) DROP.
# SPILL (the cfo, 2026-10-11, on hq_snobol4's row snobol4-the-deferred-capture-cells-...-indexes, CEO-1507 (4)): a table whose at-cap
# road is a CORRECT SLOWER ROAD -- past the cap a site keeps working without the table (an uncached path), losing nothing -- is neither
# LOUD nor a DROP. The census cannot read that from a comparison (g_sno_defer_cells' cap is a compile-time counter in emit.cpp, another
# file), so it is RULED here, table by table, and only ever with the WITNESS GATE that proves the road: the gate must exist beside this
# script, drive sites past the cap and grade them against the oracle in both modes, and fail once against a corrupted ref (CEO-1680).
# A ruling whose gate is missing reads NONE again. Key: (file basename, table name) -> gate script name.
SPILL_RULED = {("pattern_match.c", "g_sno_defer_cells"): "test_gate_sno_defer_pair_sites_past_the_cap_take_the_uncached_road.sh"}
PRIM = re.compile(r"\b(abort|exit|_exit|_Exit|longjmp|siglongjmp|__builtin_trap)\s*\(")
CALL = re.compile(r"\b([A-Za-z_]\w*)\s*\(")
ERRV = re.compile(r"(?:^|_)(err|error|errors|fatal|die|abort|refuse|refused|panic|overflow|full)(?:_|$)", re.I)
KEYWORDS = {"if", "for", "while", "switch", "return", "sizeof", "do", "else"}
OPND = r"(?P<x>(?:\*\s*)?\(?\s*\*?\s*[A-Za-z_]\w*(?:\s*(?:->|\.)\s*[A-Za-z_]\w*|\s*\[[^\]\[]{0,60}\])*\s*\)?)"
OPND_END = re.compile(OPND + r"\s*$")
OPND_START = re.compile(r"\s*" + OPND)
OP_BEFORE = re.compile(r"(<=|>=|==|!=|(?<![<\-])<|(?<![>\-])>)\s*\(?\s*$")
OP_AFTER = re.compile(r"\s*\)?\s*(<=|>=|==|!=|<(?![<=])|>(?![>=]))")


_MEMO = {}


def memo(f):
    """one computation per (function, text): the census strips and splits each file into functions from three readers."""
    def g(*a, **k):
        key = (f.__name__,) + a + tuple(sorted(k.items()))
        if key not in _MEMO:
            _MEMO[key] = f(*a, **k)
        return _MEMO[key]
    return g


@memo
def strip_c(t, pp=True):
    """t with comment and string-literal contents and (pp) preprocessor lines blanked -- every newline and offset kept."""
    out = list(t)
    i, n = 0, len(t)
    while i < n:
        c = t[i]
        if c == "/" and i + 1 < n and t[i + 1] == "/":
            j = t.find("\n", i)
            j = n if j < 0 else j
            for k in range(i, j):
                out[k] = " "
            i = j
        elif c == "/" and i + 1 < n and t[i + 1] == "*":
            j = t.find("*/", i + 2)
            j = n if j < 0 else j + 2
            for k in range(i, j):
                if t[k] != "\n":
                    out[k] = " "
            i = j
        elif c in "\"'":
            j = i + 1
            while j < n and t[j] != c:
                if t[j] == "\\":
                    j += 1
                if j < n and t[j] == "\n" and c == "'":
                    break
                j += 1
            for k in range(i + 1, min(j, n)):
                if t[k] != "\n":
                    out[k] = " "
            i = j + 1
        elif pp and c == "#" and (i == 0 or t[i - 1] == "\n"):
            e = i
            while True:
                e = t.find("\n", e)
                if e < 0:
                    e = n
                    break
                if t[e - 1] == "\\":
                    e += 1
                    continue
                break
            for k in range(i, e):
                if t[k] != "\n":
                    out[k] = " "
            i = e
        else:
            i += 1
    return "".join(out)


def match_close(s, i, o, c):
    d = 0
    for k in range(i, len(s)):
        if s[k] == o:
            d += 1
        elif s[k] == c:
            d -= 1
            if d == 0:
                return k
    return -1


@memo
def functions(s):
    """name -> [(start, end)] of each function body in stripped text s; extern "C" and namespace blocks are transparent."""
    out = {}
    d = 0
    i = 0
    while i < len(s):
        ch = s[i]
        if ch == "{":
            if d == 0 and re.search(r"\b(extern\s*\"\s*\"|namespace(\s+\w+)?)\s*$", s[max(0, i - 60):i]):
                i += 1
                continue
            if d == 0:
                j = i - 1
                while j >= 0 and s[j] in " \t\n":
                    j -= 1
                if j >= 0 and s[j] == ")":
                    dd, k = 0, j
                    while k >= 0:
                        if s[k] == ")":
                            dd += 1
                        elif s[k] == "(":
                            dd -= 1
                            if dd == 0:
                                break
                        k -= 1
                    m = re.search(r"([A-Za-z_]\w*)\s*$", s[max(0, k - 200):k])
                    e = match_close(s, i, "{", "}")
                    if m and m.group(1) not in KEYWORDS and e > 0:
                        out.setdefault(m.group(1), []).append((i, e))
                        i = e + 1
                        continue
            d += 1
        elif ch == "}":
            d = max(0, d - 1)
        i += 1
    return out


def refusing_functions(stripped):
    """Functions that REFUSE: error-shaped by name (ERRV) and reaching a primitive, directly or through other error-shaped functions.
    ⛔ NOT every function that can reach longjmp: most builtins raise an argument error somewhere, and taking all of them (1880 on
    c2cdd7480) called any at-cap branch that happened to call a builtin LOUD."""
    calls, prim = defaultdict(set), set()
    for s in stripped.values():
        for name, spans in functions(s).items():
            for a, b in spans:
                body = s[a:b]
                if PRIM.search(body):
                    prim.add(name)
                calls[name].update(CALL.findall(body))
    errshaped = {f for f in calls if ERRV.search(f)}
    callers = defaultdict(set)
    for f, cs in calls.items():
        for c in cs:
            callers[c].add(f)
    ref = {f for f in prim if f in errshaped}
    work = list(ref)
    while work:
        f = work.pop()
        for g in callers.get(f, ()):
            if g in errshaped and g not in ref:
                ref.add(g)
                work.append(g)
    return ref


def _norm(x):
    return re.sub(r"[\s()]", "", x)


def _xpat(x):
    nx = _norm(x)
    toks = [t for t in re.split(r"(->|\.|\[|\])", nx.lstrip("*")) if t]
    if not toks:
        return None
    pat = r"\s*".join(re.escape(t) for t in toks)
    return (r"\(\s*\*\s*" + pat + r"\s*\)") if nx.startswith("*") else pat


class GuardReader:
    """Classifies every comparison of a table's bound in the stripped tree, with the evidence rules in the header above."""

    def __init__(self, stripped):
        self.s = stripped
        ref = refusing_functions(stripped)
        self.refpat = re.compile(r"\b(" + "|".join(sorted(map(re.escape, ref), key=len, reverse=True)) + r")\s*\(") if ref else None
        self.refusing = ref
        self._spans, self._idx = {}, {}

    def loud(self, text):
        # ⛔ A NAME IS NOT A REFUSAL (the cfo's reading, 2026-09-24): frame_layout.c's fc_reg_full("vdj", 256) is error-shaped by name,
        # prints "TABLE FULL ... further registrations are being DROPPED" and returns -- a warned DROP -- and the first cut of this
        # reader called it LOUD because it accepted any error-shaped call. The at-cap path must REACH a primitive, itself or through a
        # refusing function; a call that only records an error (raku re.c's re_err sets p->ok = 0) is read as a drop until it is shown
        # to stop the run.
        return bool(PRIM.search(text) or (self.refpat and self.refpat.search(text)))

    def span(self, p, off):
        if p not in self._spans:
            self._spans[p] = sorted(sp for spans in functions(self.s[p]).values() for sp in spans)
        for a, b in self._spans[p]:
            if a <= off <= b:
                return a, b
        return 0, len(self.s[p])

    def indexes(self, p, name, x):
        key = (p, name)
        if key not in self._idx:
            self._idx[key] = {_norm(m.group(1)).rstrip("+-") for m in re.finditer(r"\b" + re.escape(name) + r"\s*\[([^\]\[]{0,80})\]", self.s[p])}
        return _norm(x).rstrip("+-") in self._idx[key] or ("(" + _norm(x) + ")") in self._idx[key]

    @staticmethod
    def stem(name, x):
        core = re.split(r"->|\.", _norm(x).lstrip("*"))[-1]
        st = name[:-1] if name.endswith("s") else name
        return len(st) >= 4 and (core.startswith(st) or core.startswith(name))

    @staticmethod
    def incremented(text, x):
        xp = _xpat(x)
        return bool(xp) and bool(re.search(r"(?:" + xp + r")\s*(?:\+\+|\+=)|\+\+\s*(?:" + xp + r")(?!\w)", text))

    @staticmethod
    def writes(text, name):
        n = re.escape(name)
        return bool(re.search(r"\b" + n + r"\s*\[[^\]]*\]\s*(?:\[[^\]]*\]\s*)*(?:=(?!=)|\+=|-=|\|=|(?:\.|->)\s*\w+\s*(?:\[[^\]]*\]\s*)?=(?!=))", text)
                    or re.search(r"&\s*(?:\w+\s*(?:->|\.)\s*)*" + n + r"\s*\[", text)
                    or re.search(r"\b(?:memcpy|memmove|strcpy|strncpy|strcat|snprintf|sprintf)\s*\(\s*&?\s*(?:\w+\s*(?:->|\.)\s*)*" + n + r"\b", text))

    @staticmethod
    def sites(s, bound_pat):
        for m in re.finditer(r"(?<![\w.>])(?:" + bound_pat + r")(?![\w(])", s):
            a, b = m.start(), m.end()
            pre = s[max(0, a - 160):a]
            mo = OP_BEFORE.search(pre)
            if mo:
                mx = OPND_END.search(pre[:mo.start()])
                if mx:
                    x = mx.group("x")
                    lead = len(x) - len(x.lstrip("(* \t\n"))
                    yield a - len(pre) + mx.start() + lead, x.lstrip("( \t\n"), mo.group(1), "right"
                    continue
            mo = OP_AFTER.match(s, b)
            if mo:
                mx = OPND_START.match(s, mo.end())
                if mx:
                    yield a, mx.group("x").lstrip("( \t\n"), mo.group(1), "left"

    @staticmethod
    def enclosing(s, off):
        d, k = 0, off - 1
        while k >= 0:
            c = s[k]
            if c == ")":
                d += 1
            elif c == "(":
                if d == 0:
                    m = re.search(r"([A-Za-z_]\w*)\s*$", s[max(0, k - 40):k])
                    return (m.group(1) if m else None), k
                d -= 1
            elif c in "{}" and d == 0:
                return None, -1
            k -= 1
        return None, -1

    @staticmethod
    def stmt_after(s, i):
        while i < len(s) and s[i] in " \t\n":
            i += 1
        if i < len(s) and s[i] == "{":
            return i, match_close(s, i, "{", "}") + 1
        d = 0
        for k in range(i, len(s)):
            c = s[k]
            if c in "([{":
                d += 1
            elif c in ")]}":
                d -= 1
            elif c == ";" and d <= 0:
                return i, k + 1
        return i, len(s)

    def site_class(self, p, off, x, op, side, bound_pat, name):
        s = self.s[p]
        full = (side == "right" and op in (">=", ">", "==")) or (side == "left" and op in ("<=", "<", "=="))
        kw, par = self.enclosing(s, off)
        nx = _norm(x)
        if kw == "if" and full:
            pe = match_close(s, par, "(", ")")
            a, b = self.stmt_after(s, pe + 1)
            if re.search(re.escape(nx.lstrip("*")) + r"=\(?(?:" + bound_pat + r")\b", re.sub(r"\s", "", s[a:b])):
                return "DROP-clamp"
        if full and re.match(r"[^;?]*\?\s*\(?\s*(?:" + bound_pat + r")\b", s[off:off + 200]):
            return "DROP-clamp"
        fa, fb = self.span(p, off)
        fs = s[fa:fb]
        counter = self.incremented(fs, x) and self.writes(fs, name)
        if kw == "if":
            pe = match_close(s, par, "(", ")")
            a, b = self.stmt_after(s, pe + 1)
            then, els = s[a:b], ""
            me = re.match(r"\s*else\b", s[b:b + 20])
            if me:
                a2, b2 = self.stmt_after(s, b + me.end())
                els = s[a2:b2]
            atcap = then if full else els
            # ⛔ LOUD NEEDS THE AT-CAP PATH TO BE THIS COMPARISON'S: either the compared variable is the table's counter, or the comparison
            # is the WHOLE condition of `if (x >= CAP) refuse`. core.c's `if (... && ch >= 0 && ch < IO_CHAN_MAX && ...) ... else ...`
            # takes its else when ANY clause fails -- an index check with an unrelated else read LOUD in the first cut.
            cond = s[par + 1:match_close(s, par, "(", ")")]
            sole = not re.search(r"&&|\|\|", cond)
            if atcap and self.loud(atcap) and (counter or (full and sole)):
                return "LOUD"
            if not counter:
                return "NEUTRAL"
            return "DROP-silent" if atcap.strip() else "DROP-skip"
        if not counter:
            return "NEUTRAL"
        if kw in ("for", "while"):
            pe = match_close(s, par, "(", ")")
            cond = s[par + 1:pe]
            if kw == "for":
                parts = cond.split(";")
                cond = parts[1] if len(parts) > 1 else cond
            return "DROP-truncate" if ("&&" in cond or "||" in cond) else "NEUTRAL"
        return "NEUTRAL"

    def table(self, path, name, bound, scan):
        """(guard, [evidence]) for one table: guard LOUD/DROP/NONE (or a ruled SPILL), evidence 'file:line:CLASS(var)' per attributed site."""
        sp = SPILL_RULED.get((os.path.basename(path), name))
        if sp and os.path.exists(os.path.join(os.path.dirname(os.path.abspath(__file__)), sp)):
            return "SPILL", ["gate:" + sp]
        if re.fullmatch(r"[A-Z][A-Z0-9_]*", bound):
            bp = re.escape(bound)
        elif re.fullmatch(r"[0-9]+", bound):
            bp = re.escape(bound) + (("|" + str(int(bound) - 1)) if int(bound) > 1 else "") \
                + r"|sizeof\s*\(?\s*" + re.escape(name) + r"\b\s*\)?(?:\s*/\s*sizeof\s*\(?[^)]*\)?)?"
        else:
            return "NONE", []
        kinds, ev = Counter(), []
        for q in scan:
            s = self.s.get(q)
            if s is None:
                continue
            for off, x, op, side in self.sites(s, bp):
                via_sizeof = s.startswith("sizeof", off) or bool(re.search(r"sizeof\s*\(?\s*" + re.escape(name) + r"\b", s[off:off + 60]))
                if not via_sizeof and not self.indexes(q, name, x) and not self.stem(name, x):
                    continue
                k = self.site_class(q, off, x, op, side, bp, name)
                kinds[k.split("-")[0]] += 1
                ev.append("%s%d:%s(%s)" % (("" if q == path else os.path.basename(q) + ":"), s.count("\n", 0, off) + 1, k, _norm(x)))
        g = "DROP" if kinds["DROP"] else ("LOUD" if kinds["LOUD"] else "NONE")
        return g, ev


def decl_prefix(lines, i, name):
    """The declaration's own text before NAME on line I (1-based) of comment-stripped LINES: walked back to the `;` that ends the previous
    statement, the `{` that opens the enclosing block, or the `}` of a block that is not a struct, union or enum body (whose braces belong
    to this declaration's type). ⛔ coo 2026-10-08 (CEO-1565): the physical line was read instead, so `if (e->is_const) { char eb[192];`
    and `if (!sno_const_static_on()) ... char cb[130];` read as read-only tables, and the re-flowed `} g_bid_tab[BID_TABSZ] = {` lost the
    `static const struct {` three lines above it."""
    line = lines[i - 1] if 0 < i <= len(lines) else ""
    m = re.search(r"(?<![\w.>])" + re.escape(name) + r"\s*\[", line)
    s = "\n".join(lines[max(0, i - 400):i - 1] + [line[:m.start() if m else len(line)]])
    k, d, close = len(s), 0, None
    while k > 0:
        k -= 1
        ch = s[k]
        if ch == "}":
            close = k if d == 0 else close
            d += 1
        elif ch == "{":
            if d == 0:
                k += 1
                break
            d -= 1
            if d == 0 and not re.search(r"\b(?:struct|union|enum)(?:\s+\w+)?\s*$", s[:k]):
                k = close + 1
                break
        elif ch == ";" and d == 0:
            k += 1
            break
    return s[k:]


def is_const_table(decl_line, name):
    """True when the ARRAY is read-only: a const that is not followed by a pointer star before the name (`const char *names[N]` is a
    writable array of pointers; `static const uint8_t tbl[N]` and `char *const names[N]` are not)."""
    i = decl_line.find(name + "[")
    if i < 0:
        m = re.search(r"\b" + re.escape(name) + r"\s*\[", decl_line)
        i = m.start() if m else len(decl_line)
    pre = decl_line[:i]
    # a struct's own fields are not the array's qualifiers: `static const struct { const char *nm; ... } g_bid_tab[BID_TABSZ]` is
    # read-only, and the `*` of its first field read it as a writable array of pointers
    while re.search(r"\{[^{}]*\}", pre):
        pre = re.sub(r"\{[^{}]*\}", " ", pre)
    cs = [m.end() for m in re.finditer(r"\bconst\b", pre)]
    return bool(cs) and "*" not in pre[cs[-1]:]


def classify_guards(rows, texts):
    """rows (as main builds them) -> rows extended with (guard, const, evidence). Macro bounds are read in the declaring file and in
    every file that #includes it by name (a struct field declared in a header is filled elsewhere); literal bounds in the declaring
    file only, because a number is not a name."""
    stripped = {p: strip_c(t) for p, t in texts.items()}
    gr = GuardReader(stripped)
    includers = defaultdict(set)
    for p, t in texts.items():
        for m in re.finditer(r'^\s*#\s*include\s*"([^"]+)"', t, re.M):
            includers[os.path.basename(m.group(1))].add(p)
    lines_of = {}
    out = []
    for r in rows:
        p, i, scope, name, bound = r[0], r[1], r[2], r[3], r[4]
        if scope not in ("file", "static", "field"):
            # function-scope arrays are CEO-1231's second population and get their own reader; until it lands they carry no guard
            # reading at all, rather than one the file-scope rules were never calibrated for
            out.append(tuple(r[:7]) + ("", "", ""))
            continue
        scan = [p]
        if re.fullmatch(r"[A-Z][A-Z0-9_]*", bound) and p.endswith((".h", ".hpp")):
            scan += sorted(includers.get(os.path.basename(p), ()))
        g, ev = gr.table(p, name, bound, scan)
        if p not in lines_of:
            lines_of[p] = strip_c(texts[p], pp=False).split("\n")
        c = is_const_table(decl_prefix(lines_of[p], i, name) + name + "[", name)
        out.append(tuple(r[:7]) + (g, "const" if c else "", " ".join(ev)))
    return out, gr


