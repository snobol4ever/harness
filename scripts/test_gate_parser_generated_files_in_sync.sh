#!/usr/bin/env bash
# stale-binary preflight (row test-gate-scripts-that-grade-scrip-refuse-on-a-stale-binary-census-widened, hq_T 2026-09-05)
"$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/util_require_fresh.sh" --gate "$(basename "${BASH_SOURCE[0]}" .sh)" || exit $?
# test_gate_parser_generated_files_in_sync.sh -- every committed bison/flex output matches a fresh regeneration from its .y/.l source.
# hq_T 2026-09-04, row parser-sources-and-generated-files-in-sync-gate-in-make-test (minted by ceo).
#
# ⛔⭐ THE TRAP THIS EXISTS FOR, MEASURED TWICE IN ONE DAY BY TWO DIFFERENT SESSIONS (ceo 16:25 on raku.y; hq_C 18:1x on snobol4.l):
# the generated parsers are TRACKED FILES and the Makefile compiles them as-is with NO bison/flex rule. So editing a .y or .l changes
# NOTHING -- `make` succeeds, the binary is rebuilt, every board stays green, and the edit is simply not in the program. The build
# does not fail, does not warn, and cannot: from make's point of view nothing that it knows about changed. Both sessions lost a build
# to it before noticing, and neither was careless -- editing the grammar is the obviously correct way to change the grammar.
# ⭐ WHY IT SURVIVED THIS LONG: nothing in the blocking set regenerates a grammar, so the entire regeneration path can be dead (as it
# WAS, for ten days -- bison could not run at all until seat03 cured it 2026-09-04) without one board going red. A capability nobody
# exercises is not a capability anybody has, and this gate is what exercises it.
#
# ⛔ RED IS "THE COMMITTED OUTPUT IS NOT WHAT THE SOURCE SAYS", WHICH IS NOT THE SAME AS "THE SOURCE IS NEWER". mtime is not evidence
# here: a fresh clone gives every file the same checkout time, and `touch` on a .y would red a perfectly consistent tree. This gate
# regenerates and DIFFS -- the only question that has a true answer independent of how the tree arrived on disk.
# ⛔ #line DIRECTIVES ARE IGNORED, and only they: bison bakes the input path into #line, so the one legitimately path-dependent line
# is excluded and everything else -- tables, actions, guards, includes -- is compared byte for byte.
# ⛔ IT REFUSES rc=2 RATHER THAN REPORTING A FALSE RED when it cannot measure: no bison/flex (gen_tools_ready), or a tool version
# other than the pinned pair. A DIFFERENT bison emits DIFFERENT tables from identical input, so an unpinned run reds every grammar at
# once and names the tree as the culprit when the toolchain is what moved. Refusing keeps "I could not measure" from wearing the
# clothes of "your parsers are stale".
# ⛔ THE SCRATCH COPY IS THE POINT: generation happens under mktemp -d, NEVER in src/parsers. A gate that regenerates in place would
# "pass" by overwriting the very evidence it was asked to grade, and would leave the tree dirty on every run.
#
# Denominator is PRINTED, and the disk is censused against the table rather than trusted to match it: a .y/.l that no table row
# covers is RED (its output is regenerated by nobody and this gate would otherwise silently not grade it), and a produced file with no
# committed twin is RED (a generated file that was never committed builds here and nowhere else).
# Usage: bash ../harness/scripts/test_gate_parser_generated_files_in_sync.sh      Exit: 0 in sync · 1 out of sync/uncovered · 2 cannot measure.
set -uo pipefail
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"; SCRIP="$(cd "$HERE/../../SCRIP" && pwd)"
GATE_NAME=parser-generated-files-in-sync
. "$HERE/lib_build_flags.sh"
. "$HERE/lib_gen_parsers.sh"
refuse() { echo "⛔ GATE UNPROVEN(2) [$GATE_NAME]: $*" >&2; exit 2; }
gen_tools_ready || refuse "bison/flex cannot generate -- see the lib_build_flags refusal above"
[ "$BF_BISON_VERSION" = "$GEN_BISON_PIN" ] || refuse "bison is $BF_BISON_VERSION, the committed outputs are pinned to $GEN_BISON_PIN -- a different bison emits different tables from identical input, so this run would red every grammar and blame the tree"
[ "$BF_FLEX_VERSION" = "$GEN_FLEX_PIN" ] || refuse "flex is $BF_FLEX_VERSION, the committed outputs are pinned to $GEN_FLEX_PIN -- same reason as bison above"
P="$SCRIP/src/parsers"
[ -d "$P" ] || refuse "no $P -- cannot census grammars"
WORK="$(mktemp -d)"; trap 'rm -rf "$WORK"' EXIT
echo "== $GATE_NAME -- bison $BF_BISON_VERSION, flex $BF_FLEX_VERSION${BISON_PKGDATADIR:+ (BISON_PKGDATADIR=$BISON_PKGDATADIR)}"
rows=0; checked=0; bad=0
# Census the DISK first and require the table to cover it. A table that has quietly fallen behind the tree is the one failure this
# gate cannot afford, because it presents as a clean green run over a smaller population than the reader believes it graded.
ondisk="$(cd "$P" && ls -1 */*.y */*.l 2>/dev/null | sort)"
[ -n "$ondisk" ] || refuse "censused $P and found zero .y/.l sources -- a gate that cannot see its population must never print 0"
intable="$(gen_parsers_table | awk -F'\t' '{print $1 "/" $2}' | sort)"
uncovered="$(comm -23 <(printf '%s\n' "$ondisk") <(printf '%s\n' "$intable"))"
missing="$(comm -13 <(printf '%s\n' "$ondisk") <(printf '%s\n' "$intable"))"
if [ -n "$uncovered" ]; then
    bad=$((bad + 1))
    echo "RED  grammar on disk that no lib_gen_parsers.sh row covers -- nobody regenerates it and this gate does not grade it:"
    printf '%s\n' "$uncovered" | sed 's/^/       /'
fi
if [ -n "$missing" ]; then
    bad=$((bad + 1))
    echo "RED  lib_gen_parsers.sh row whose source is not on disk -- the table is ahead of the tree:"
    printf '%s\n' "$missing" | sed 's/^/       /'
fi
while IFS=$'\t' read -r dir src out cmd; do
    [ -n "${dir:-}" ] || continue
    rows=$((rows + 1))
    w="$WORK/$dir.$src"; mkdir -p "$w"
    if [ ! -f "$P/$dir/$src" ]; then echo "RED  $dir/$src: source named by the table is not on disk"; bad=$((bad + 1)); continue; fi
    cp "$P/$dir/$src" "$w/$src"
    if ! ( cd "$w" && eval "$cmd" ) >"$w/.genlog" 2>&1; then
        echo "RED  $dir/$src: regeneration FAILED with the pinned tools -- the committed output cannot be reproduced from this source"
        sed 's/^/       /' "$w/.genlog" | head -5; bad=$((bad + 1)); continue
    fi
    # Compare everything the run PRODUCED, rather than a predicted list: `bison -d` emits a .tab.h nobody named, and discovering the
    # artifacts from the generator is what keeps this gate honest when a flag changes what gets written.
    produced="$(cd "$w" && ls -1 | grep -v -x -F -e "$src" -e .genlog | sort)"
    if [ -z "$produced" ]; then echo "RED  $dir/$src: the generator exited 0 and produced nothing"; bad=$((bad + 1)); continue; fi
    # ⛔ THE POST-PROCESS IS PART OF GENERATION AND THIS GATE MUST APPLY IT TOO (ceo CEO-851).  bison and flex emit a skeleton calling
    # malloc and free; RULES.md line 29 forbids them in generated output as much as anywhere, so the committed twin is swept.  A gate
    # that diffed raw generator output against the swept twin would be RED FOREVER on exactly the difference the post-process exists to
    # create -- which is what it did on all nine files at 36f0edab5 until this line.  gen_postprocess lives in lib_gen_parsers.sh beside
    # the invocation table, so this gate and the regenerator cannot drift apart.
    ( cd "$w" && gen_postprocess $produced )
    for f in $produced; do
        checked=$((checked + 1))
        if [ ! -f "$P/$dir/$f" ]; then
            echo "RED  $dir/$f: generated by $src but NOT COMMITTED -- this builds here and nowhere else"; bad=$((bad + 1)); continue
        fi
        if ! diff -q <(grep -v '^#line' "$P/$dir/$f") <(grep -v '^#line' "$w/$f") >/dev/null 2>&1; then
            n=$(diff <(grep -v '^#line' "$P/$dir/$f") <(grep -v '^#line' "$w/$f") | grep -c '^[<>]')
            echo "RED  $dir/$f: committed output does NOT match a fresh regeneration from $dir/$src ($n non-#line lines differ)"
            echo "       cure: bash ../harness/scripts/regenerate_parser_and_lexer_from_sources.sh, then commit $dir/$src and its outputs TOGETHER"
            bad=$((bad + 1))
        fi
    done
done < <(gen_parsers_table)
echo "-- graded $checked generated file(s) from $rows grammar source(s) across $(gen_parsers_table | cut -f1 | sort -u | wc -l) parser dirs"
[ "$checked" -gt 0 ] || refuse "graded zero generated files -- zero-work-examined is indistinguishable from all-clean"
if [ "$bad" -ne 0 ]; then echo "GATE RED(1) [$GATE_NAME]: $bad problem(s) above -- a .y/.l edit is not in the build until its generated twin is regenerated and committed"; exit 1; fi
echo "GATE GREEN(0) [$GATE_NAME]: every committed generated file matches a fresh regeneration from its source"
exit 0
