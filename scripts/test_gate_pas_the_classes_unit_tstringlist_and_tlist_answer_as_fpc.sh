# test_gate_pas_the_classes_unit_tstringlist_and_tlist_answer_as_fpc.sh -- `uses classes` gives TStringList and TList that answer as fpc's do:
# Add, AddObject, Append, Insert, Delete, Clear, Exchange, Move, IndexOf, IndexOfName, IndexOfObject, Find, Sort and CustomSort (order-preserving for equal
# keys, which fpc leaves undefined), Sorted with Duplicates, CaseSensitive, Assign, Equals, Text (get and set, #10 #13 #13#10), CommaText,
# Delimiter, QuoteChar, StrictDelimiter and DelimitedText (get and set), Names, Values, ValueFromIndex, the default Strings property, the
# EListError messages; TList: Add, Insert, Delete, Remove, IndexOf, First, Last, Exchange, Clear, Count and the default Items property.
#
# MEASURED 2026-10-14 by hq_pascal for PasRosetta's empty-output class (ceo CEO-1709): 12 of its programs name `uses classes` and died at
# "no unit classes.pas beside it and no SCRIP prelude unit of that name". THE CURE: src/parsers/pascal/prelude/classes.pas, written in Pascal
# from FPC 3.2.2's rtl/objpas/classes (stringl.inc, lists.inc) with storage in dynamic-array fields; pascal_prelude_units.inc regenerated by
# util_gen_pascal_prelude_units.py; sysutils gains CompareStr, AnsiCompareStr and AnsiCompareText; the lowerer treats a string element of a
# dynamic-array field as a string (pas_dyn_elem_is_string) and TList.Sort takes a TListSortCompare.
# OPEN, NOT GRADED HERE: TObjectList and contnrs; TStrings; LoadFromFile / SaveToFile beyond the line loop; a for-in over a TStringList; TAlignment;
# the typecast TListSortCompare(@fn) and PData(list.Items[i])^.field, which top-rank-per-group and collections-6 need.
#
# ARMS: stringlists (the wide witness) and tokenizing (DelimitedText, Sort, Insert/Delete, Sorted + dupIgnore, CommaText) against fpc -Mobjfpc,
# both modes, cut LIVE from the fpc RTL's own classes unit. MEASURED on the parent (in-tree swap): both red. FAIL_ONCE=1 corrupts stringlists.
"$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/util_require_fresh.sh" --gate "$(basename "${BASH_SOURCE[0]}" .sh)" || exit $?
set -uo pipefail
G="$(basename "${BASH_SOURCE[0]}" .sh)"
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"; ROOT="$(cd "$HERE/../../SCRIP" && pwd)"
SCRIP="${SCRIP_BIN:-$ROOT/scrip}"; [ -x "$SCRIP" ] || { echo "⛔ GATE REFUSE(2) [$G]: no scrip at $SCRIP"; exit 2; }
RT_DIR="${RT_DIR:-$ROOT/out}"; [ -f "$RT_DIR/libscrip_rt.so" ] || { echo "⛔ GATE REFUSE(2) [$G]: no runtime at $RT_DIR/libscrip_rt.so"; exit 2; }
FPC="${FPC_BIN:-/usr/bin/fpc}"; [ -x "$FPC" ] || { echo "⛔ GATE REFUSE(2) [$G]: no fpc at $FPC -- every expectation is CUT FROM THE ORACLE"; exit 2; }
T=$(mktemp -d) || exit 2; trap 'rm -rf "$T"' EXIT
RC=0; N=0
run() { local m="$1" p="$2"
  if [ "$m" = m3 ]; then ( cd "$T" && LD_LIBRARY_PATH="$RT_DIR" timeout -k 5 20s "$SCRIP" --run "$p.pas" </dev/null >"$T/o" 2>"$T/e" ); return $?; fi
  ( cd "$T" && timeout -k 5 20s "$SCRIP" --compile -o "$T/$p.s" "$p.pas" </dev/null >/dev/null 2>&1 && cc -m64 -no-pie "$p.s" -o "$p.m4" -L"$RT_DIR" -lscrip_rt -lm -Wl,-rpath,"$RT_DIR" >/dev/null 2>&1 ) || { echo "  ⛔ $p m4: did not compile and link"; return 125; }
  ( cd "$T" && timeout -k 5 20s "./$p.m4" </dev/null >"$T/o" 2>"$T/e" ); return $?; }
fpcrun() { local mode="$2"; mkdir -p "$T/fpc"; ( cd "$T" && "$FPC" $mode -v0 -FE"$T/fpc" -o"$T/$1.fpc" "$T/$1.pas" >/dev/null 2>&1 ) || { echo "⛔ GATE REFUSE(2) [$G]: fpc $mode would not compile $1"; exit 2; }; ( cd "$T" && timeout -k 5 20s "./$1.fpc" </dev/null >"$T/$1.want" 2>/dev/null ); echo $?; }
cat > "$T/stringlists.pas" <<'PAS'
program stringlists;
{$mode objfpc}
uses sysutils, classes;
function ByLength(List: TStringList; I1, I2: Integer): Integer;
begin
  Result := Length(List[I1]) - Length(List[I2])
end;
function Desc(Item1, Item2: Pointer): Integer;
begin
  Result := 0
end;
var
  s, t: TStringList; l: TList; a, b, c: integer; i, idx: integer; found: boolean;
begin
  s := TStringList.Create;
  s.Add('pear'); s.Add('fig'); s.Add('banana'); s.Add('kiwis'); s.Add('Zebra123'); s.Add('apple12');
  s.CustomSort(@ByLength);
  for i := 0 to s.Count - 1 do write(s[i], ' '); writeln;
  s.Sort; for i := 0 to s.Count - 1 do write(s[i], ' '); writeln;
  s.CaseSensitive := true; s.Sort; for i := 0 to s.Count - 1 do write(s[i], ' '); writeln;
  s.Exchange(0, 5); s.Move(1, 3); writeln(s.Text);
  s.Text := 'one' + #10 + 'two' + #13#10 + 'three' + #10; writeln(s.Count, ' ', s[2], ' ', s.IndexOf('two'));
  s.Clear;
  s.CommaText := 'a, "b c",d,,e'; writeln(s.Count, '|', s[1], '|', s[3], '|', s.CommaText, '|', s.DelimitedText);
  s.StrictDelimiter := true; s.Delimiter := ';'; s.DelimitedText := ' x ; y;z'; writeln(s.Count, '[', s[0], '][', s[1], ']');
  s.Clear; s.Values['k1'] := 'v1'; s.Values['k2'] := 'v2'; s.Values['k1'] := 'w'; writeln(s.Text, s.Values['k2'], s.Names[1], s.IndexOfName('k2'), s.ValueFromIndex[0]);
  s.Clear; s.Sorted := true; s.Duplicates := dupIgnore;
  s.Add('m'); s.Add('c'); s.Add('x'); s.Add('c'); found := s.Find('x', idx); writeln(s.Count, ' ', found, ' ', idx, ' ', s.IndexOf('m'), ' ', s.Text);
  t := TStringList.Create; t.Assign(s); t.Sorted := false; t.Add('end'); writeln(t.Count, ' ', t.Equals(s), ' ', s.Equals(s));
  try s[9] := 'q'; except on E: Exception do writeln('err ', E.Message) end;
  try writeln(t[7]) except on E: Exception do writeln('err ', E.Message) end;
  l := TList.Create;
  l.Add(@a); l.Add(@c); l.Insert(1, @b);
  writeln(l.Count, ' ', l.IndexOf(@b), ' ', l.IndexOf(@c), ' ', l.Remove(@a), ' ', l.Count, ' ', l.IndexOf(@a));
  l.Exchange(0, 1); writeln(l.IndexOf(@b), ' ', l.First = Pointer(@c), ' ', l.Last = Pointer(@b));
  l.Delete(0); l.Clear; writeln(l.Count);
  l.Free; t.Free; s.Free
end.
PAS
cat > "$T/tokenizing.pas" <<'PAS'
program tokenizing;
{$mode objfpc}
uses sysutils, classes;
var t: TStringList; i: integer;
begin
  t := TStringList.Create;
  t.Delimiter := ',';
  t.DelimitedText := 'Hello,How,Are,You,Today';
  t.Delimiter := '.';
  writeln(Format('to: "%s"', [t.DelimitedText]), ' ', t.Count);
  t.Add('banana'); t.Add('Apple'); t.Add('cherry'); t.Add('apple');
  t.Sort;
  for i := 0 to t.Count - 1 do write(t[i], ';'); writeln;
  writeln(t.IndexOf('CHERRY'), ' ', t.IndexOf('zzz'));
  t.Append('tail'); t.Delete(0); t.Insert(1, 'mid'); writeln(t.Text);
  t.Sorted := true; t.Duplicates := dupIgnore; t.Add('mid'); t.Add('zed'); writeln(t.CommaText, ' ', t.Count);
